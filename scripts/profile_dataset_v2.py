"""Profile the REAL energy DuckDB database for gold-question authoring.

Reads databases/duckdb/analytics.duckdb (table electric_power), prints a
profile, and writes references/sql_gold/dataset_profile_v2.md. Read-only.

Re-runnable: python scripts/profile_dataset_v2.py
"""

from __future__ import annotations

from pathlib import Path
import sys

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = PROJECT_ROOT / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from local_agentic_analytics.tools.duckdb_tool import DuckDBTool

DB_PATH = PROJECT_ROOT / "databases" / "duckdb" / "analytics.duckdb"
OUTPUT_PATH = PROJECT_ROOT / "references" / "sql_gold" / "dataset_profile_v2.md"
TABLE = "electric_power"

NUMERIC_COLUMNS = (
    "Global_active_power",
    "Global_reactive_power",
    "Voltage",
    "Global_intensity",
    "Sub_metering_1",
    "Sub_metering_2",
    "Sub_metering_3",
)
ALL_COLUMNS = ("datetime",) + NUMERIC_COLUMNS


def _df_to_md(df) -> str:
    try:
        return df.to_markdown(index=False)
    except Exception:
        return "```\n" + df.to_string(index=False) + "\n```"


def main() -> None:
    if not DB_PATH.is_file():
        raise SystemExit(f"Database not found: {DB_PATH}")

    tool = DuckDBTool(str(DB_PATH))
    sections: list[str] = []

    def emit(title: str, body: str) -> None:
        block = f"## {title}\n\n{body}\n"
        print(f"\n{'=' * 70}\n{title}\n{'=' * 70}\n{body}")
        sections.append(block)

    # Row count + datetime extent
    extent = tool.execute_query(
        f"""
        SELECT
            COUNT(*) AS row_count,
            MIN(datetime) AS min_datetime,
            MAX(datetime) AS max_datetime,
            COUNT(DISTINCT CAST(datetime AS DATE)) AS distinct_days
        FROM {TABLE};
        """
    )
    emit("Row count and datetime extent", _df_to_md(extent))

    # Distinct dates
    distinct_dates = tool.execute_query(
        f"""
        SELECT CAST(datetime AS DATE) AS day, COUNT(*) AS rows
        FROM {TABLE}
        GROUP BY day
        ORDER BY day;
        """
    )
    emit(
        f"Distinct dates available ({len(distinct_dates)} days)",
        _df_to_md(distinct_dates),
    )

    # Month coverage
    months = tool.execute_query(
        f"""
        SELECT
            STRFTIME(datetime, '%Y-%m') AS month,
            COUNT(*) AS rows,
            MIN(CAST(datetime AS DATE)) AS first_day,
            MAX(CAST(datetime AS DATE)) AS last_day
        FROM {TABLE}
        GROUP BY month
        ORDER BY month;
        """
    )
    emit("Month coverage", _df_to_md(months))

    # Hour-of-day coverage (to confirm hour filters are valid)
    hours = tool.execute_query(
        f"""
        SELECT EXTRACT(HOUR FROM datetime) AS hour_of_day, COUNT(*) AS rows
        FROM {TABLE}
        GROUP BY hour_of_day
        ORDER BY hour_of_day;
        """
    )
    emit("Hour-of-day coverage", _df_to_md(hours))

    # Per-column min/max/avg + null counts
    select_parts = []
    for col in NUMERIC_COLUMNS:
        select_parts.append(
            f"MIN({col}) AS {col}_min, MAX({col}) AS {col}_max, "
            f"AVG({col}) AS {col}_avg, "
            f"COUNT(*) FILTER (WHERE {col} IS NULL) AS {col}_nulls"
        )
    stats = tool.execute_query(
        f"SELECT {', '.join(select_parts)} FROM {TABLE};"
    )
    # Reshape wide -> long for readability
    long_rows = []
    row = stats.iloc[0]
    for col in NUMERIC_COLUMNS:
        long_rows.append(
            {
                "column": col,
                "min": row[f"{col}_min"],
                "max": row[f"{col}_max"],
                "avg": row[f"{col}_avg"],
                "null_count": row[f"{col}_nulls"],
            }
        )
    import pandas as pd

    emit(
        "Per-column min / max / avg / null counts (numeric)",
        _df_to_md(pd.DataFrame(long_rows)),
    )

    # Null count for datetime too
    dt_nulls = tool.execute_query(
        f"SELECT COUNT(*) FILTER (WHERE datetime IS NULL) AS datetime_nulls FROM {TABLE};"
    )
    emit("datetime null count", _df_to_md(dt_nulls))

    # Sample rows
    sample = tool.execute_query(
        f"SELECT {', '.join(ALL_COLUMNS)} FROM {TABLE} ORDER BY datetime LIMIT 5;"
    )
    emit("Sample rows (first 5 by datetime)", _df_to_md(sample))

    tool.close()

    header = (
        "# Energy Dataset Profile v2 (REAL database)\n\n"
        f"- Source DB: `databases/duckdb/analytics.duckdb`\n"
        f"- Table: `{TABLE}`\n"
        "- Generated by: `scripts/profile_dataset_v2.py` (read-only)\n"
        "- Purpose: ground v2 gold questions in real, existing dates/values.\n"
    )
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(header + "\n" + "\n".join(sections), encoding="utf-8")
    print(f"\nWrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
